from typing import Final

TILE_SIDE: Final[int] = 8
SCREEN_COLUMNS: Final[int] = 32
SCREEN_ROWS: Final[int] = 30
SCREEN_WIDTH: Final[int] = SCREEN_COLUMNS * TILE_SIDE
SCREEN_HEIGHT: Final[int] = SCREEN_ROWS * TILE_SIDE
NAMETABLE_SIZE: Final[int] = SCREEN_COLUMNS * SCREEN_ROWS

COLOR_BITS: Final[int] = 2
COLORS_PER_PALETTE: Final[int] = 1 << COLOR_BITS
PALETTES_PER_LAYER: Final[int] = 4
PALETTE_SIZE: Final[int] = 2 * PALETTES_PER_LAYER * COLORS_PER_PALETTE
MASTER_COLOR_COUNT: Final[int] = 64

ATTRIBUTE_CELL_TILES: Final[int] = 2
ATTRIBUTE_CELLS_PER_BYTE: Final[int] = 2
ATTRIBUTE_COLUMNS: Final[int] = SCREEN_COLUMNS // ATTRIBUTE_CELL_TILES
ATTRIBUTE_ROWS: Final[int] = SCREEN_ROWS // ATTRIBUTE_CELL_TILES
ATTRIBUTE_TABLE_SIDE: Final[int] = 8
ATTRIBUTE_TABLE_SIZE: Final[int] = ATTRIBUTE_TABLE_SIDE * ATTRIBUTE_TABLE_SIDE

TILES_PER_TABLE: Final[int] = 256
TILE_BYTES: Final[int] = 2 * TILE_SIDE
PATTERN_TABLE_SIZE: Final[int] = TILES_PER_TABLE * TILE_BYTES
BACKGROUND_TABLE: Final[int] = 0
SPRITE_TABLE: Final[int] = 1
PATTERN_TABLE_COUNT: Final[int] = 2
PATTERNS_SIZE: Final[int] = PATTERN_TABLE_COUNT * PATTERN_TABLE_SIZE

SPRITE_COUNT: Final[int] = 64
SPRITE_BYTES: Final[int] = 4
SPRITE_MEMORY_SIZE: Final[int] = SPRITE_COUNT * SPRITE_BYTES
SPRITE_Y_OFFSET: Final[int] = 0
SPRITE_TILE_OFFSET: Final[int] = 1
SPRITE_ATTRIBUTES_OFFSET: Final[int] = 2
SPRITE_X_OFFSET: Final[int] = 3
SPRITE_PALETTE_MASK: Final[int] = 0x03
SPRITE_SCANLINE_DELAY: Final[int] = 1
SPRITES_PER_SCANLINE: Final[int] = 8
HIDDEN_SPRITE_Y: Final[int] = 0xF0

FIRST_GLYPH: Final[int] = 0x20
LAST_GLYPH: Final[int] = 0x7E
GLYPH_COUNT: Final[int] = LAST_GLYPH - FIRST_GLYPH + 1
