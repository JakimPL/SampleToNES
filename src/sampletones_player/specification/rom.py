from typing import Final

ROM_MAGIC: Final[bytes] = b"NES\x1a"

PROGRAM_UNIT_SIZE: Final[int] = 0x4000
PATTERN_UNIT_SIZE: Final[int] = 0x2000

MAGIC_OFFSET: Final[int] = 0
PROGRAM_UNITS_OFFSET: Final[int] = MAGIC_OFFSET + len(ROM_MAGIC)
PATTERN_UNITS_OFFSET: Final[int] = PROGRAM_UNITS_OFFSET + 1
BOARD_FLAGS_OFFSET: Final[int] = PATTERN_UNITS_OFFSET + 1
SYSTEM_FLAGS_OFFSET: Final[int] = BOARD_FLAGS_OFFSET + 1
PADDING_OFFSET: Final[int] = SYSTEM_FLAGS_OFFSET + 1
PADDING_SIZE: Final[int] = 8
ROM_HEADER_SIZE: Final[int] = PADDING_OFFSET + PADDING_SIZE

VERTICAL_MIRRORING_FLAG: Final[int] = 0x01
BATTERY_FLAG: Final[int] = 0x02
TRAINER_FLAG: Final[int] = 0x04
ALTERNATIVE_LAYOUT_FLAG: Final[int] = 0x08
MAPPER_NIBBLE_SHIFT: Final[int] = 4
MAPPER_HIGH_NIBBLE_MASK: Final[int] = 0xF0

NROM_MAPPER: Final[int] = 0
