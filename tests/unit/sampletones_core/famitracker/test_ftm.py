class TestWriteFtm:
    def test_writes_a_parseable_file(self, project_fixture: ProjectFixture, tmp_path: Path) -> None:
        path = tmp_path / "module.ftm"
        write_ftm(path, project_fixture.project)
        parsed = parse_ftm(path.read_bytes())
        assert parsed.version == FTM_VERSION
        assert len(parsed.instruments) == 5

    def test_empty_volume_marker_when_no_volume(self, project_fixture: ProjectFixture) -> None:
        parsed = _parsed(project_fixture)
        pattern = next(p for p in parsed.patterns if p.channel == int(ChannelId.SQUARE1) and p.index == 0)
        note_off_row = next(row for row in pattern.rows if row.row_number == 2)
        assert note_off_row.volume == EMPTY_VOLUME
