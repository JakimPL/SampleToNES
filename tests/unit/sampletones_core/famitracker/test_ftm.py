ALL_BLOCKS = [
    BLOCK_PARAMS,
    BLOCK_INFO,
    BLOCK_HEADER,
    BLOCK_INSTRUMENTS,
    BLOCK_SEQUENCES,
    BLOCK_FRAMES,
    BLOCK_PATTERNS,
    BLOCK_DPCM_SAMPLES,
    BLOCK_COMMENTS,
]


def _module_bytes(fixture: ProjectFixture) -> bytes:
    return module_to_ftm_bytes(project_to_module(fixture.project))


def _parsed(fixture: ProjectFixture) -> ParsedModule:
    return parse_ftm(_module_bytes(fixture))


def _pooled(parsed: ParsedModule, sequence_type: SequenceKind, index: int) -> ParsedSequence:
    return next(
        sequence
        for sequence in parsed.sequences
        if sequence.sequence_type == int(sequence_type) and sequence.index == index
    )


class TestFileFraming:
    def test_ends_with_end_marker(self, project_fixture: ProjectFixture) -> None:
        assert _module_bytes(project_fixture).endswith(FTM_END_MARKER)

    def test_version_matches(self, project_fixture: ProjectFixture) -> None:
        assert _parsed(project_fixture).version == FTM_VERSION

    def test_every_block_present_with_expected_version(self, project_fixture: ProjectFixture) -> None:
        versions = _parsed(project_fixture).block_versions
        for block in ALL_BLOCKS:
            assert versions[block.name] == block.version


