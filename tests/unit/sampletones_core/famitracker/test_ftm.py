class TestPatternsBlock:
    def _pattern(self, parsed: ParsedModule, channel: ChannelId, index: int):
        return next(p for p in parsed.patterns if p.channel == int(channel) and p.index == index)

    def test_only_used_channels_have_patterns(self, project_fixture: ProjectFixture) -> None:
        channels = {pattern.channel for pattern in _parsed(project_fixture).patterns}
        assert channels == {int(ChannelId.SQUARE1), int(ChannelId.NOISE)}

    def test_instrument_row(self, project_fixture: ProjectFixture) -> None:
        parsed = _parsed(project_fixture)
        pattern = self._pattern(parsed, ChannelId.SQUARE1, 0)
        row = next(row for row in pattern.rows if row.row_number == 0)
        assert (row.note, row.octave) == (1, 3)
        assert row.instrument == 0
        assert row.volume == 10

    def test_note_off_row(self, project_fixture: ProjectFixture) -> None:
        parsed = _parsed(project_fixture)
        pattern = self._pattern(parsed, ChannelId.SQUARE1, 0)
        row = next(row for row in pattern.rows if row.row_number == 2)
        assert row.note == int(NoteValue.HALT)
        assert row.instrument == EMPTY_INSTRUMENT

    def test_volume_only_row(self, project_fixture: ProjectFixture) -> None:
        parsed = _parsed(project_fixture)
        pattern = self._pattern(parsed, ChannelId.SQUARE1, 0)
        row = next(row for row in pattern.rows if row.row_number == 4)
        assert row.note == int(NoteValue.NONE)
        assert row.instrument == EMPTY_INSTRUMENT
        assert row.volume == 5

    def test_noise_row_period_note(self, project_fixture: ProjectFixture) -> None:
        parsed = _parsed(project_fixture)
        pattern = self._pattern(parsed, ChannelId.NOISE, 0)
        row = next(row for row in pattern.rows if row.row_number == 0)
        assert (row.note, row.octave) == (5, 0)


